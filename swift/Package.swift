// swift-tools-version:5.9
// Swift wrapper around the Rust core. Every platform app depends on this package.
//
// Run scripts/build-core.sh (or .ps1 on Windows) first: it builds the Rust
// static library into swift/lib/ and regenerates the bindings in Sources/.

import PackageDescription

let libDir = "\(Context.packageDirectory)/lib"

// Extra system libraries the Rust standard library needs when linked statically.
let rustSystemLibs: [LinkerSetting] = [
    .linkedLibrary("ws2_32", .when(platforms: [.windows])),
    .linkedLibrary("userenv", .when(platforms: [.windows])),
    .linkedLibrary("bcrypt", .when(platforms: [.windows])),
    .linkedLibrary("ntdll", .when(platforms: [.windows])),
    .linkedLibrary("pthread", .when(platforms: [.linux])),
    .linkedLibrary("dl", .when(platforms: [.linux])),
    .linkedLibrary("m", .when(platforms: [.linux])),
]

let package = Package(
    name: "DBClientCore",
    platforms: [.macOS(.v13)],
    products: [
        .library(name: "DBClientCore", targets: ["DBClientCore"]),
    ],
    targets: [
        // C header + module map generated by UniFFI.
        .target(
            name: "DBClientCoreFFI",
            path: "Sources/DBClientCoreFFI",
            linkerSettings: [
                .unsafeFlags(["-L\(libDir)"]),
                .linkedLibrary("dbclient_core"),
            ] + rustSystemLibs
        ),
        // Swift API generated by UniFFI, plus any hand-written helpers.
        .target(
            name: "DBClientCore",
            dependencies: ["DBClientCoreFFI"],
            path: "Sources/DBClientCore"
        ),
        .testTarget(
            name: "DBClientCoreTests",
            dependencies: ["DBClientCore"],
            path: "Tests/DBClientCoreTests"
        ),
    ]
)

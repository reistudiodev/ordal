// swift-tools-version:5.9
// Swift wrapper around the Rust core. Every platform app depends on this package.
//
// Run scripts/build-core.sh (or .ps1 on Windows) first: it builds the Rust
// static library into swift/lib/ and regenerates the bindings in Sources/.

import PackageDescription

let libDir = "\(Context.packageDirectory)/lib"

// Extra system libraries the statically linked Rust core needs: the standard
// library, plus OS services used by the drivers (DNS/proxy settings for the
// MongoDB resolver, the keychain, TLS root certificates).
let rustSystemLibs: [LinkerSetting] = [
    .linkedFramework("SystemConfiguration", .when(platforms: [.macOS])),
    .linkedFramework("Security", .when(platforms: [.macOS])),
    .linkedFramework("CoreFoundation", .when(platforms: [.macOS])),
    .linkedLibrary("ws2_32", .when(platforms: [.windows])),
    .linkedLibrary("userenv", .when(platforms: [.windows])),
    .linkedLibrary("bcrypt", .when(platforms: [.windows])),
    .linkedLibrary("ntdll", .when(platforms: [.windows])),
    .linkedLibrary("advapi32", .when(platforms: [.windows])),
    .linkedLibrary("crypt32", .when(platforms: [.windows])),
    .linkedLibrary("secur32", .when(platforms: [.windows])),
    .linkedLibrary("ncrypt", .when(platforms: [.windows])),
    .linkedLibrary("iphlpapi", .when(platforms: [.windows])),
    .linkedLibrary("dnsapi", .when(platforms: [.windows])),
    .linkedLibrary("pthread", .when(platforms: [.linux])),
    .linkedLibrary("dl", .when(platforms: [.linux])),
    .linkedLibrary("m", .when(platforms: [.linux])),
    .linkedLibrary("dbus-1", .when(platforms: [.linux])),
]

let package = Package(
    name: "DBClientCore",
    platforms: [.macOS(.v14)],
    products: [
        .library(name: "DBClientCore", targets: ["DBClientCore"]),
        // Platform-neutral view models shared by the macOS, Windows and Linux apps.
        .library(name: "DBClientKit", targets: ["DBClientKit"]),
    ],
    targets: [
        // C header + module map generated by UniFFI.
        .target(
            name: "DBClientCoreFFI",
            path: "Sources/DBClientCoreFFI",
            linkerSettings: [
                .unsafeFlags(["-L\(libDir)"]),
                .linkedLibrary("dbclient_core"),
            ] + rustSystemLibs
        ),
        // Swift API generated by UniFFI, plus any hand-written helpers.
        .target(
            name: "DBClientCore",
            dependencies: ["DBClientCoreFFI"],
            path: "Sources/DBClientCore"
        ),
        // Hand-written app state and view models (no UI framework imports).
        .target(
            name: "DBClientKit",
            dependencies: ["DBClientCore"],
            path: "Sources/DBClientKit"
        ),
        .testTarget(
            name: "DBClientKitTests",
            dependencies: ["DBClientKit"],
            path: "Tests/DBClientKitTests"
        ),
        .testTarget(
            name: "DBClientCoreTests",
            dependencies: ["DBClientCore"],
            path: "Tests/DBClientCoreTests"
        ),
    ]
)

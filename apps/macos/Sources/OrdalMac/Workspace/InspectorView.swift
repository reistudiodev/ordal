import AppKit
import OrdalKit
import SwiftUI

/// The selected cell. In a table tab it is also the editor: the input
/// matches the column's type, and a change is staged (yellow) until the
/// table's changes are reviewed and applied.
struct InspectorView: View {
    let workspace: WorkspaceModel

    var body: some View {
        if let cell = workspace.inspected {
            if let tab = editableTab(for: cell), let meta = tab.pager.columnMeta(cell.column.name) {
                CellEditor(cell: cell, meta: meta, pager: tab.pager)
                    .id("\(cell.row):\(cell.columnIndex):\(tab.pager.version)")
            } else {
                ReadOnlyCell(cell: cell, reason: readOnlyReason(for: cell))
            }
        } else {
            ContentUnavailableView("Nothing selected", systemImage: "sidebar.right", description: Text("Click a cell to see its full value. In a table tab, double-click to edit it."))
        }
    }

    private func tab(for cell: WorkspaceModel.InspectedCell) -> TableTabModel? {
        guard let id = cell.tableTab, case .table(let t)? = workspace.tabs.first(where: { $0.id == id }) else { return nil }
        return t
    }

    private func editableTab(for cell: WorkspaceModel.InspectedCell) -> TableTabModel? {
        guard let t = tab(for: cell), t.pager.canEdit, t.pager.columnMeta(cell.column.name)?.editable == true else { return nil }
        return t
    }

    private func readOnlyReason(for cell: WorkspaceModel.InspectedCell) -> String? {
        guard let t = tab(for: cell) else { return "Query results are read-only. Open the table to edit rows." }
        if let reason = t.pager.meta?.readOnlyReason { return reason }
        guard let meta = t.pager.columnMeta(cell.column.name) else { return nil }
        if meta.isKey { return "Key columns identify the row and can't be edited here." }
        if !meta.editable { return "This column is generated by the database." }
        return nil
    }
}

private struct Header: View {
    let name: String
    let detail: String
    let value: Value

    var body: some View {
        HStack(alignment: .firstTextBaseline) {
            VStack(alignment: .leading, spacing: 2) {
                Text(name).font(.headline)
                Text(detail).font(.caption).foregroundStyle(.secondary)
            }
            Spacer()
            Button("Copy") {
                NSPasteboard.general.clearContents()
                NSPasteboard.general.setString(value.inspectorText, forType: .string)
            }
            .controlSize(.small)
        }
    }
}

private struct ReadOnlyCell: View {
    let cell: WorkspaceModel.InspectedCell
    let reason: String?

    var body: some View {
        VStack(alignment: .leading, spacing: Space.s) {
            Header(name: cell.column.name,
                   detail: "\(cell.column.typeName.isEmpty ? "\(cell.column.kind)" : cell.column.typeName) · row \(cell.row + 1)",
                   value: cell.value)
            if let reason {
                Label(reason, systemImage: "lock").font(.caption).foregroundStyle(.secondary)
            }
            Divider()
            ScrollView {
                Text(cell.value.inspectorText)
                    .font(.system(.body, design: .monospaced))
                    .foregroundStyle(cell.value.isNull ? .secondary : .primary)
                    .textSelection(.enabled)
                    .frame(maxWidth: .infinity, alignment: .leading)
            }
        }
        .padding(Space.m)
    }
}

/// A type-aware editor for one cell.
private struct CellEditor: View {
    let cell: WorkspaceModel.InspectedCell
    let meta: ColumnMeta
    let pager: TablePager
    @State private var text = ""
    @State private var isNull = false
    @FocusState private var focused: Bool

    private var current: Value { pager.row(at: cell.row)?.cells[cell.columnIndex] ?? cell.value }
    private var isStaged: Bool { pager.isStaged(row: cell.row, column: cell.columnIndex) }

    private var parsed: Result<Value, CellValueParser.ParseError> {
        isNull ? .success(.null) : CellValueParser.parse(text, for: meta)
    }

    private var canStage: Bool {
        if case .success(let v) = parsed { return v != current }
        return false
    }

    var body: some View {
        VStack(alignment: .leading, spacing: Space.s) {
            Header(name: meta.name, detail: detail, value: current)
            Divider()
            if isNull {
                HStack {
                    Text("NULL").font(.body.monospaced().italic()).foregroundStyle(.secondary)
                    Spacer()
                    Button("Enter a value") { isNull = false; focused = true }
                }
                .padding(.vertical, Space.s)
            } else {
                input
            }

            switch parsed {
            case .failure(let e):
                Label(e.message, systemImage: "exclamationmark.circle").font(.caption).foregroundStyle(.red)
            case .success:
                Text(hint).font(.caption).foregroundStyle(.secondary)
            }

            HStack(spacing: Space.s) {
                if meta.nullable && !isNull {
                    Button("Set NULL") { isNull = true }
                }
                if isStaged {
                    Button("Revert") { revert() }
                        .help("Back to the value in the database")
                }
                Spacer()
                Button("Stage Change") { stage() }
                    .keyboardShortcut(.return, modifiers: .command)
                    .disabled(!canStage)
                    .help("Mark this change; save it with Review Changes (⌘↩)")
            }
            .controlSize(.small)
            Spacer()
        }
        .padding(Space.m)
        .onAppear(perform: load)
    }

    @ViewBuilder
    private var input: some View {
        if !meta.enumValues.isEmpty {
            Picker("Value", selection: $text) {
                ForEach(meta.enumValues, id: \.self) { Text($0).tag($0) }
            }
            .labelsHidden()
        } else {
            switch meta.kind {
            case .bool:
                Picker("Value", selection: $text) {
                    Text("true").tag("true")
                    Text("false").tag("false")
                }
                .pickerStyle(.segmented)
                .labelsHidden()
            case .json, .text, .other:
                TextEditor(text: $text)
                    .font(.system(.body, design: .monospaced))
                    .frame(minHeight: 120, maxHeight: 360)
                    .scrollContentBackground(.hidden)
                    .padding(Space.hairline)
                    .background(.background, in: RoundedRectangle(cornerRadius: 6))
                    .overlay(RoundedRectangle(cornerRadius: 6).strokeBorder(.separator))
                    .focused($focused)
                if meta.kind == .json {
                    Button("Format JSON") { if let pretty = prettyJSON(text) { text = pretty } }
                        .controlSize(.small)
                }
            default:
                HStack {
                    TextField(meta.name, text: $text)
                        .textFieldStyle(.roundedBorder)
                        .font(.body.monospaced())
                        .focused($focused)
                        .onSubmit { if canStage { stage() } }
                    helperButton
                }
            }
        }
    }

    @ViewBuilder
    private var helperButton: some View {
        switch meta.kind {
        case .timestamp, .timestampTz:
            Button("Now") { text = Self.now(withZone: meta.kind == .timestampTz) }.controlSize(.small)
        case .date:
            Button("Today") { text = String(Self.now(withZone: false).prefix(10)) }.controlSize(.small)
        case .uuid:
            Button("Generate") { text = UUID().uuidString.lowercased() }.controlSize(.small)
        default:
            EmptyView()
        }
    }

    private var detail: String {
        var parts = [meta.typeName]
        parts.append(meta.nullable ? "nullable" : "not null")
        parts.append("row \(cell.row + 1)")
        return parts.joined(separator: " · ")
    }

    private var hint: String {
        if isStaged { return "Changed, not saved yet. Review Changes saves everything at once." }
        switch meta.kind {
        case .int: return "A whole number."
        case .decimal, .float: return "A number. Use a point for decimals."
        case .date: return "YYYY-MM-DD"
        case .timestamp: return "YYYY-MM-DD HH:MM:SS"
        case .timestampTz: return "YYYY-MM-DD HH:MM:SS with an optional zone, e.g. +07:00"
        case .json: return "Any JSON value."
        default: return "Press ⌘↩ to stage."
        }
    }

    private func load() {
        isNull = current.isNull
        text = isNull ? defaultText : CellValueParser.editText(current)
    }

    /// A sensible starting value when a NULL cell gets a value.
    private var defaultText: String {
        if let first = meta.enumValues.first { return first }
        return meta.kind == .bool ? "false" : ""
    }

    private func stage() {
        guard case .success(let v) = parsed else { return }
        pager.stage(row: cell.row, column: cell.columnIndex, value: v)
    }

    private func revert() {
        pager.revert(row: cell.row, column: cell.columnIndex)
        load()
    }

    private func prettyJSON(_ s: String) -> String? {
        guard let data = s.data(using: .utf8),
              let obj = try? JSONSerialization.jsonObject(with: data, options: [.fragmentsAllowed]),
              let out = try? JSONSerialization.data(withJSONObject: obj, options: [.prettyPrinted, .sortedKeys, .fragmentsAllowed])
        else { return nil }
        return String(data: out, encoding: .utf8)
    }

    private static func now(withZone: Bool) -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = withZone ? "yyyy-MM-dd HH:mm:ssxxx" : "yyyy-MM-dd HH:mm:ss"
        return f.string(from: Date())
    }
}

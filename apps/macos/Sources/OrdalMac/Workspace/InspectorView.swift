/// Redesigned Cell Inspector & Editor:
/// Features clean typography, dedicated type-aware badges, a visual JSON Tree Explorer,
/// pretty/compact formatting tools, instant copy feedback, and prominent staged status.
struct InspectorView: View {
    let workspace: WorkspaceModel

    var body: some View {
        if let cell = workspace.inspected {
            let changeAction: (() -> Void)? = {
                guard workspace.config.kind.isSQL, let t = tab(for: cell) else { return nil }
                return {
                    workspace.presentChangeColumnType(
                        column: cell.column.name,
                        currentType: cell.column.typeName,
                        tablePath: t.path,
                        tableName: t.title
                    )
                }
            }()
            if let tab = editableTab(for: cell), let meta = tab.pager.columnMeta(cell.column.name) {
                CellEditor(cell: cell, meta: meta, pager: tab.pager, onChangeType: changeAction)
                    .id("\(cell.row):\(cell.columnIndex):\(tab.pager.version)")
            } else {
                ReadOnlyCell(cell: cell, reason: readOnlyReason(for: cell), onChangeType: changeAction)
            }
        } else {
            ContentUnavailableView {
                Label("Nothing Selected", systemImage: "sidebar.right")
            } description: {
                Text("Click any table or query result cell to inspect its value in detail.")
            }
        }
    }

    private func tab(for cell: WorkspaceModel.InspectedCell) -> TableTabModel? {
        guard let id = cell.tableTab, case .table(let t)? = workspace.tabs.first(where: { $0.id == id }) else { return nil }
        return t
    }

    private func editableTab(for cell: WorkspaceModel.InspectedCell) -> TableTabModel? {
        guard let t = tab(for: cell), t.pager.canEdit, t.pager.columnMeta(cell.column.name)?.editable == true else { return nil }
        return t
    }

    private func readOnlyReason(for cell: WorkspaceModel.InspectedCell) -> String? {
        guard let t = tab(for: cell) else { return "Query results are read-only. Open the table to edit rows." }
        if let reason = t.pager.meta?.readOnlyReason { return reason }
        guard let meta = t.pager.columnMeta(cell.column.name) else { return nil }
        if meta.isKey { return "Key columns identify the row and cannot be edited directly." }
        if !meta.editable { return "This column is generated by the database engine." }
        return nil
    }
}

// MARK: - Header

private struct InspectorHeader: View {
    let name: String
    let kind: ValueKind
    let typeName: String
    let isNullable: Bool
    let isKey: Bool
    let rowIndex: Int
    let value: Value
    var onChangeType: (() -> Void)? = nil
    @State private var copied = false

    var body: some View {
        VStack(alignment: .leading, spacing: 6) {
            HStack(alignment: .center, spacing: 8) {
                typeIcon
                    .font(.title3)

                Text(name)
                    .font(.headline)
                    .lineLimit(1)

                if isKey {
                    Image(systemName: "key.fill")
                        .foregroundStyle(.yellow)
                        .font(.caption)
                        .help("Primary Key")
                }

                Spacer()

                Button {
                    NSPasteboard.general.clearContents()
                    NSPasteboard.general.setString(value.inspectorText, forType: .string)
                    copied = true
                    Task {
                        try? await Task.sleep(for: .seconds(1.5))
                        copied = false
                    }
                } label: {
                    if copied {
                        HStack(spacing: 4) {
                            Image(systemName: "checkmark")
                            Text("Copied")
                        }
                        .foregroundStyle(.green)
                    } else {
                        HStack(spacing: 4) {
                            Image(systemName: "doc.on.doc")
                            Text("Copy")
                        }
                    }
                }
                .buttonStyle(.borderless)
                .controlSize(.small)
            }

            HStack(spacing: 6) {
                Pill(text: typeName.isEmpty ? "\(kind)".uppercased() : typeName.uppercased(), color: pillColor)
                if let onChangeType {
                    Button(action: onChangeType) {
                        Image(systemName: "pencil")
                            .font(.system(size: 9, weight: .bold))
                            .foregroundStyle(.secondary)
                    }
                    .buttonStyle(.plain)
                    .help("Change column data type…")
                }
                Pill(text: isNullable ? "NULLABLE" : "NOT NULL", color: isNullable ? .secondary : .indigo)
                Pill(text: "ROW \(rowIndex + 1)", color: .secondary)
            }
        }
        .padding(.bottom, 2)
    }

    @ViewBuilder
    private var typeIcon: some View {
        switch kind {
        case .json:
            Image(systemName: "curlybraces.square.fill").foregroundStyle(.green)
        case .int, .float, .decimal:
            Image(systemName: "number.square.fill").foregroundStyle(.blue)
        case .text:
            Image(systemName: "textformat.characters").foregroundStyle(.teal)
        case .date, .time, .timestamp:
            Image(systemName: "calendar.badge.clock").foregroundStyle(.orange)
        case .bool:
            Image(systemName: "switch.2").foregroundStyle(.purple)
        case .uuid:
            Image(systemName: "key.horizontal.fill").foregroundStyle(.indigo)
        case .bytes:
            Image(systemName: "memorychip.fill").foregroundStyle(.brown)
        default:
            Image(systemName: "doc.text.fill").foregroundStyle(.secondary)
        }
    }

    private var pillColor: Color {
        switch kind {
        case .json: return .green
        case .int, .float, .decimal: return .blue
        case .text: return .teal
        case .date, .time, .timestamp: return .orange
        case .bool: return .purple
        case .uuid: return .indigo
        default: return .secondary
        }
    }
}

// MARK: - Read-Only Cell

private struct ReadOnlyCell: View {
    let cell: WorkspaceModel.InspectedCell
    let reason: String?
    var onChangeType: (() -> Void)? = nil
    @State private var viewMode: ViewMode = .tree

    private enum ViewMode: String, CaseIterable, Identifiable {
        case tree = "Tree"
        case raw = "Raw"
        var id: String { rawValue }
    }

    private var isJSON: Bool {
        cell.column.kind == .json || cell.value.inspectorText.trimmingCharacters(in: .whitespacesAndNewlines).hasPrefix("{")
    }

    var body: some View {
        VStack(alignment: .leading, spacing: Space.s) {
            InspectorHeader(
                name: cell.column.name,
                kind: cell.column.kind,
                typeName: cell.column.typeName,
                isNullable: true,
                isKey: false,
                rowIndex: cell.row,
                value: cell.value,
                onChangeType: onChangeType
            )

            if let reason {
                Label(reason, systemImage: "lock")
                    .font(.caption)
                    .foregroundStyle(.secondary)
                    .padding(.vertical, 2)
            }

            Divider()

            if isJSON, let doc = DocValue.parse(cell.value.inspectorText) {
                HStack {
                    Picker("Mode", selection: $viewMode) {
                        ForEach(ViewMode.allCases) { Text($0.rawValue).tag($0) }
                    }
                    .pickerStyle(.segmented)
                    .labelsHidden()
                    .controlSize(.small)
                    .frame(width: 140)

                    Spacer()

                    Text("\(cell.value.inspectorText.count) chars")
                        .font(.caption2)
                        .foregroundStyle(.secondary)
                }

                if viewMode == .tree {
                    ScrollView {
                        DocNodeView(value: doc, key: nil)
                            .frame(maxWidth: .infinity, alignment: .leading)
                            .padding(Space.s)
                    }
                    .background(Color(nsColor: .textBackgroundColor))
                    .cornerRadius(8)
                    .overlay(RoundedRectangle(cornerRadius: 8).strokeBorder(Color(nsColor: .separatorColor)))
                } else {
                    rawTextView
                }
            } else {
                rawTextView
            }
        }
        .padding(Space.m)
    }

    private var rawTextView: some View {
        ScrollView {
            Text(cell.value.inspectorText)
                .font(.system(.body, design: .monospaced))
                .foregroundStyle(cell.value.isNull ? .secondary : .primary)
                .textSelection(.enabled)
                .frame(maxWidth: .infinity, alignment: .leading)
                .padding(Space.s)
        }
        .background(Color(nsColor: .textBackgroundColor))
        .cornerRadius(8)
        .overlay(RoundedRectangle(cornerRadius: 8).strokeBorder(Color(nsColor: .separatorColor)))
    }
}

// MARK: - Cell Editor

private struct CellEditor: View {
    let cell: WorkspaceModel.InspectedCell
    let meta: ColumnMeta
    let pager: TablePager
    var onChangeType: (() -> Void)? = nil
    @State private var text = ""
    @State private var isNull = false
    @State private var viewMode: EditorViewMode = .editor
    @FocusState private var focused: Bool

    private enum EditorViewMode: String, CaseIterable, Identifiable {
        case editor = "Editor"
        case tree = "Tree"
        var id: String { rawValue }
    }

    private var current: Value { pager.row(at: cell.row)?.cells[cell.columnIndex] ?? cell.value }
    private var isStaged: Bool { pager.isStaged(row: cell.row, column: cell.columnIndex) }

    private var parsed: Result<Value, CellValueParser.ParseError> {
        isNull ? .success(.null) : CellValueParser.parse(text, for: meta)
    }

    private var canStage: Bool {
        if case .success(let v) = parsed { return v != current }
        return false
    }

    private var isJSON: Bool {
        meta.kind == .json || text.trimmingCharacters(in: .whitespacesAndNewlines).hasPrefix("{")
    }

    var body: some View {
        VStack(alignment: .leading, spacing: Space.s) {
            InspectorHeader(
                name: meta.name,
                kind: meta.kind,
                typeName: meta.typeName,
                isNullable: meta.nullable,
                isKey: meta.isKey,
                rowIndex: cell.row,
                value: current,
                onChangeType: onChangeType
            )

            if isStaged {
                HStack(spacing: 8) {
                    Image(systemName: "pencil.circle.fill").foregroundStyle(.orange)
                    VStack(alignment: .leading, spacing: 1) {
                        Text("Staged Change").font(.caption.weight(.semibold))
                        Text("Not saved to database yet (Review Changes ⌘↩)").font(.caption2).foregroundStyle(.secondary)
                    }
                    Spacer()
                    Button("Revert") { revert() }
                        .buttonStyle(.bordered)
                        .controlSize(.mini)
                        .help("Back to the value in the database")
                }
                .padding(8)
                .background(Color.orange.opacity(0.12))
                .cornerRadius(6)
            }

            Divider()

            if isNull {
                HStack {
                    Text("NULL").font(.body.monospaced().italic()).foregroundStyle(.secondary)
                    Spacer()
                    Button("Enter a value") { isNull = false; focused = true }
                        .controlSize(.small)
                }
                .padding(Space.s)
                .background(Color(nsColor: .textBackgroundColor))
                .cornerRadius(6)
            } else {
                inputSection
            }

            switch parsed {
            case .failure(let e):
                Label(e.message, systemImage: "exclamationmark.triangle.fill")
                    .font(.caption)
                    .foregroundStyle(.red)
            case .success:
                Text(hint)
                    .font(.caption)
                    .foregroundStyle(.secondary)
            }

            // Action toolbar
            HStack(spacing: Space.s) {
                if meta.nullable && !isNull {
                    Button("Set NULL") { isNull = true }
                        .controlSize(.small)
                }
                helperButton

                Spacer()

                Button("Stage Change") { stage() }
                    .buttonStyle(.borderedProminent)
                    .keyboardShortcut(.return, modifiers: .command)
                    .disabled(!canStage)
                    .help("Mark this change; save with Review Changes (⌘↩)")
                    .controlSize(.small)
            }

            Spacer()
        }
        .padding(Space.m)
        .onAppear(perform: load)
    }

    @ViewBuilder
    private var inputSection: some View {
        if !meta.enumValues.isEmpty {
            Picker("Value", selection: $text) {
                ForEach(meta.enumValues, id: \.self) { Text($0).tag($0) }
            }
            .labelsHidden()
        } else {
            switch meta.kind {
            case .bool:
                Picker("Value", selection: $text) {
                    Text("true").tag("true")
                    Text("false").tag("false")
                }
                .pickerStyle(.segmented)
                .labelsHidden()
            case .json, .text, .other:
                VStack(spacing: 4) {
                    if isJSON {
                        HStack {
                            Picker("View Mode", selection: $viewMode) {
                                ForEach(EditorViewMode.allCases) { Text($0.rawValue).tag($0) }
                            }
                            .pickerStyle(.segmented)
                            .labelsHidden()
                            .controlSize(.mini)
                            .frame(width: 130)

                            Spacer()

                            Button {
                                if let pretty = prettyJSON(text) { text = pretty }
                            } label: {
                                Label("Format", systemImage: "wand.and.stars")
                            }
                            .buttonStyle(.borderless)
                            .controlSize(.mini)
                            .help("Format JSON (indent with 2 spaces)")

                            Button {
                                if let compact = compactJSON(text) { text = compact }
                            } label: {
                                Label("Minify", systemImage: "arrow.right.to.line.compact")
                            }
                            .buttonStyle(.borderless)
                            .controlSize(.mini)
                            .help("Compact JSON")
                        }
                        .padding(.horizontal, 2)
                    }

                    if viewMode == .tree, isJSON, let doc = DocValue.parse(text) {
                        ScrollView {
                            DocNodeView(value: doc, key: nil)
                                .frame(maxWidth: .infinity, alignment: .leading)
                                .padding(Space.s)
                        }
                        .frame(minHeight: 140, maxHeight: 340)
                        .background(Color(nsColor: .textBackgroundColor))
                        .cornerRadius(8)
                        .overlay(RoundedRectangle(cornerRadius: 8).strokeBorder(Color(nsColor: .separatorColor)))
                    } else {
                        TextEditor(text: $text)
                            .font(.system(.body, design: .monospaced))
                            .frame(minHeight: 140, maxHeight: 340)
                            .scrollContentBackground(.hidden)
                            .padding(6)
                            .background(Color(nsColor: .textBackgroundColor))
                            .cornerRadius(8)
                            .overlay(RoundedRectangle(cornerRadius: 8).strokeBorder(Color(nsColor: .separatorColor)))
                            .focused($focused)
                    }
                }
            default:
                HStack {
                    TextField(meta.name, text: $text)
                        .textFieldStyle(.roundedBorder)
                        .font(.body.monospaced())
                        .focused($focused)
                        .onSubmit { if canStage { stage() } }
                }
            }
        }
    }

    @ViewBuilder
    private var helperButton: some View {
        switch meta.kind {
        case .timestamp, .timestampTz:
            Button("Now") { text = Self.now(withZone: meta.kind == .timestampTz) }.controlSize(.small)
        case .date:
            Button("Today") { text = String(Self.now(withZone: false).prefix(10)) }.controlSize(.small)
        case .uuid:
            Button("UUID") { text = UUID().uuidString.lowercased() }.controlSize(.small)
        default:
            EmptyView()
        }
    }

    private var hint: String {
        if isStaged { return "Changed, pending review (⌘↩)." }
        switch meta.kind {
        case .int: return "Whole integer."
        case .decimal, .float: return "Floating point number."
        case .date: return "Format: YYYY-MM-DD"
        case .timestamp: return "Format: YYYY-MM-DD HH:MM:SS"
        case .timestampTz: return "Format: YYYY-MM-DD HH:MM:SS+00:00"
        case .json: return "Valid JSON object or array."
        default: return "Press ⌘↩ to stage edit."
        }
    }

    private func load() {
        isNull = current.isNull
        text = isNull ? defaultText : CellValueParser.editText(current)
    }

    private var defaultText: String {
        if let first = meta.enumValues.first { return first }
        return meta.kind == .bool ? "false" : ""
    }

    private func stage() {
        guard case .success(let v) = parsed else { return }
        pager.stage(row: cell.row, column: cell.columnIndex, value: v)
    }

    private func revert() {
        pager.revert(row: cell.row, column: cell.columnIndex)
        load()
    }

    private func prettyJSON(_ s: String) -> String? {
        guard let data = s.data(using: .utf8),
              let obj = try? JSONSerialization.jsonObject(with: data, options: [.fragmentsAllowed]),
              let out = try? JSONSerialization.data(withJSONObject: obj, options: [.prettyPrinted, .sortedKeys, .fragmentsAllowed])
        else { return nil }
        return String(data: out, encoding: .utf8)
    }

    private func compactJSON(_ s: String) -> String? {
        guard let data = s.data(using: .utf8),
              let obj = try? JSONSerialization.jsonObject(with: data, options: [.fragmentsAllowed]),
              let out = try? JSONSerialization.data(withJSONObject: obj, options: [.fragmentsAllowed])
        else { return nil }
        return String(data: out, encoding: .utf8)
    }

    private static func now(withZone: Bool) -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = withZone ? "yyyy-MM-dd HH:mm:ssxxx" : "yyyy-MM-dd HH:mm:ss"
        return f.string(from: Date())
    }
}

// MARK: - Interactive JSON Tree View

private struct DocNodeView: View {
    let value: DocValue
    let key: String?
    @State private var isExpanded = true

    var body: some View {
        switch value {
        case .object(let fields):
            VStack(alignment: .leading, spacing: 2) {
                HStack(spacing: 4) {
                    Button {
                        isExpanded.toggle()
                    } label: {
                        Image(systemName: isExpanded ? "chevron.down" : "chevron.right")
                            .font(.caption2)
                            .frame(width: 14)
                    }
                    .buttonStyle(.plain)

                    if let key {
                        Text(key)
                            .font(.system(.caption, design: .monospaced).weight(.semibold))
                            .foregroundStyle(.primary)
                        Text(":")
                            .font(.caption)
                            .foregroundStyle(.secondary)
                    }

                    Text("Object (\(fields.count))")
                        .font(.system(.caption2, design: .monospaced))
                        .padding(.horizontal, 4)
                        .padding(.vertical, 1)
                        .background(Color.green.opacity(0.15))
                        .cornerRadius(3)
                        .foregroundStyle(.green)
                }

                if isExpanded {
                    VStack(alignment: .leading, spacing: 3) {
                        ForEach(fields, id: \.key) { f in
                            DocNodeView(value: f.value, key: f.key)
                        }
                    }
                    .padding(.leading, 16)
                }
            }

        case .array(let items):
            VStack(alignment: .leading, spacing: 2) {
                HStack(spacing: 4) {
                    Button {
                        isExpanded.toggle()
                    } label: {
                        Image(systemName: isExpanded ? "chevron.down" : "chevron.right")
                            .font(.caption2)
                            .frame(width: 14)
                    }
                    .buttonStyle(.plain)

                    if let key {
                        Text(key)
                            .font(.system(.caption, design: .monospaced).weight(.semibold))
                        Text(":")
                            .font(.caption)
                            .foregroundStyle(.secondary)
                    }

                    Text("Array (\(items.count))")
                        .font(.system(.caption2, design: .monospaced))
                        .padding(.horizontal, 4)
                        .padding(.vertical, 1)
                        .background(Color.blue.opacity(0.15))
                        .cornerRadius(3)
                        .foregroundStyle(.blue)
                }

                if isExpanded {
                    VStack(alignment: .leading, spacing: 3) {
                        ForEach(Array(items.enumerated()), id: \.offset) { i, it in
                            DocNodeView(value: it, key: "[\(i)]")
                        }
                    }
                    .padding(.leading, 16)
                }
            }

        default:
            HStack(spacing: 4) {
                Rectangle().fill(Color.clear).frame(width: 14, height: 1)

                if let key {
                    Text(key)
                        .font(.system(.caption, design: .monospaced).weight(.semibold))
                        .foregroundStyle(.primary)
                    Text(":")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                }

                Text(value.preview)
                    .font(.system(.caption, design: .monospaced))
                    .foregroundStyle(valueColor)
                    .textSelection(.enabled)

                Text(value.typeName)
                    .font(.system(size: 9, design: .monospaced))
                    .padding(.horizontal, 3)
                    .padding(.vertical, 1)
                    .background(Color.secondary.opacity(0.15))
                    .cornerRadius(2)
                    .foregroundStyle(.secondary)
            }
        }
    }

    private var valueColor: Color {
        switch value {
        case .string: return .green
        case .number, .int32, .double, .long, .decimal: return .blue
        case .bool: return .purple
        case .null: return .secondary
        default: return .primary
        }
    }
}
